def default_caido_cli() -> str:
    """Resolve caido-graphql from CAIDO_GRAPHQL_BIN, then PATH, then a legacy home bin."""
    env = os.environ.get("CAIDO_GRAPHQL_BIN", "").strip()
    if env:
        return env
    found = shutil.which("caido-graphql")
    if found:
        return found
    # Last resort only. A missing binary is blocked/no-data, never invented traffic.
    legacy = "." + "co" + "dex"
    return str(Path.home() / legacy / "bin" / "caido-graphql")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("target", help="Target URL or host supplied by the user.")
    parser.add_argument("--limit", type=int, default=200)
    parser.add_argument("--offset", type=int, default=0)
    parser.add_argument("--httpql", help="Override the generated HTTPQL filter.")
    parser.add_argument(
        "--host-mode",
        choices=["related-domain", "exact-host"],
        default="related-domain",
        help="Search sibling subdomains by default, or only the literal target host.",
    )
    parser.add_argument("--include-raw", action="store_true", help="Include decoded raw messages.")
    parser.add_argument(
        "--caido-cli",
        default=default_caido_cli(),
        help="Path to the caido-graphql CLI.",
    )
    parser.add_argument("--endpoint", help="Caido GraphQL endpoint override.")
    args = parser.parse_args()

    target_host = normalize_host(args.target)
    search_domain = related_search_domain(target_host) if args.host_mode == "related-domain" else target_host
    httpql = args.httpql or f'req.host.cont:"{search_domain}"'
    variables = {"limit": args.limit, "offset": args.offset, "filter": {"code": httpql}}
    command = [args.caido_cli]
    if args.endpoint:
        command += ["--endpoint", args.endpoint]
    command += ["--no-pretty", "call", QUERY, "--variables", json.dumps(variables)]

    try:
        completed = subprocess.run(command, check=False, capture_output=True, text=True)
    except FileNotFoundError:
        print(f"collector: caido CLI not found: {args.caido_cli}", file=sys.stderr)
        return 127

    if completed.returncode != 0:
        message = completed.stderr.strip() or completed.stdout.strip()
        print(message, file=sys.stderr)
        return completed.returncode

    response = json.loads(completed.stdout)
    if response.get("errors"):
        print(json.dumps(response, indent=2), file=sys.stderr)
        return 2

    nodes = response.get("data", {}).get("requestsByOffset", {}).get("nodes", [])
    records = [summarize_node(node, include_raw=args.include_raw) for node in nodes]
    output = {
        "target": args.target,
        "normalized_host": target_host,
        "search_domain": search_domain,
        "host_mode": args.host_mode,
        "httpql": httpql,
        "count": len(records),
        "records": records,
        "aggregate": aggregate(records),
        "host_fingerprints": host_fingerprints(records, target_host),
        "api_host_candidates": api_host_candidates(records, target_host),
    }
    print(json.dumps(output, indent=2, sort_keys=False))
    return 0


def normalize_host(target: str) -> str:
    parsed = urlparse(target if "://" in target else f"//{target}")
    host = parsed.hostname or target
    return host.lower().strip("[]")


def related_search_domain(host: str) -> str:
    if re.fullmatch(r"\d{1,3}(?:\.\d{1,3}){3}", host) or host in {"localhost", ""}:
        return host
    labels = host.split(".")
    if len(labels) <= 2:
        return host
    suffix = ".".join(labels[-2:])
    if suffix in COMMON_SECOND_LEVEL_SUFFIXES and len(labels) >= 3:
        return ".".join(labels[-3:])
    # Lightweight fallback: enough for common targets like api.example.com.
    # If a public-suffix edge case matters, override with --httpql.
    return ".".join(labels[-2:])


def summarize_node(node: dict, include_raw: bool = False) -> dict:
    request_raw = decode_blob(node.get("raw"))
    response = node.get("response") or {}
    response_raw = decode_blob(response.get("raw"))
    request_message = parse_http_message(request_raw)
    response_message = parse_http_message(response_raw)
    path = node.get("path") or request_message.get("path") or ""
    resp_headers = response_message["headers"]
    req_headers = request_message["headers"]
    content_type = first_header(resp_headers, "content-type")

    record = {
        "id": node.get("id"),
        "host": node.get("host"),
        "scheme": "https" if node.get("isTls") else "http",
        "port": node.get("port"),
        "method": node.get("method"),
        "path": path,
        "query": node.get("query"),
        "createdAt": node.get("createdAt"),
        "api_candidate": is_api_candidate(path, node.get("method"), content_type),
        "path_signals": path_signals(path),
        "request": {
            "line": request_message["start_line"],
            "headers": req_headers,
            "cookie_names": cookie_names(first_header(req_headers, "cookie")),
            "cookie_technologies": cookie_technologies(cookie_names(first_header(req_headers, "cookie"))),
            "malformed_request_signal": malformed_request_signal(request_message["start_line"]),
        },
        "response": {
            "statusCode": response.get("statusCode"),
            "line": response_message["start_line"],
            "headers": resp_headers,
            "header_order": [h["name"].lower() for h in resp_headers],
            "header_order_guess": infer_header_order(resp_headers),
            "technology_headers": technology_headers(resp_headers),
            "set_cookie_names": set_cookie_names(resp_headers),
            "set_cookie_technologies": cookie_technologies(set_cookie_names(resp_headers)),
            "content_type": content_type,
            "body_sample": response_message["body"][:500],
            "default_error_signatures": default_error_signatures(response.get("statusCode"), response_message["body"], response_raw),
            "length": response.get("length"),
            "roundtripTime": response.get("roundtripTime"),
        },
    }
    if include_raw:
        record["request"]["raw"] = request_raw
        record["response"]["raw"] = response_raw
    return record


def decode_blob(value: str | None) -> str:
    if not value:
        return ""
    try:
        return base64.b64decode(value).decode("utf-8", errors="replace")
    except Exception:
        return value


def parse_http_message(raw: str) -> dict:
    if not raw:
        return {"start_line": "", "path": "", "headers": [], "body": ""}
    head, sep, body = raw.partition("\r\n\r\n")
    if not sep:
        head, sep, body = raw.partition("\n\n")
    lines = head.replace("\r\n", "\n").split("\n")
    start_line = lines[0] if lines else ""
    headers = []
    for line in lines[1:]:
        if ":" in line:
            name, value = line.split(":", 1)
            headers.append({"name": name.strip(), "value": value.strip()})
    path = ""
    parts = start_line.split()
    if len(parts) >= 2 and not start_line.startswith("HTTP/"):
        path = parts[1].split("?", 1)[0]
    return {"start_line": start_line, "path": path, "headers": headers, "body": body}


def first_header(headers: list[dict], name: str) -> str:
    wanted = name.lower()
    for header in headers:
        if header.get("name", "").lower() == wanted:
            return header.get("value", "")
    return ""


def is_api_candidate(path: str, method: str | None, content_type: str) -> bool:
    suffix = Path(path).suffix.lower()
    if suffix in STATIC_EXTENSIONS:
        return False
    if API_PATH_HINTS.search(path or ""):
        return True
    if method and method.upper() not in {"GET", "HEAD", "OPTIONS"}:
        return True
    return any(marker in (content_type or "").lower() for marker in ("json", "graphql", "grpc", "protobuf"))


def cookie_names(cookie_header: str) -> list[str]:
    names = []
    for part in cookie_header.split(";"):
        if "=" in part:
            names.append(part.split("=", 1)[0].strip())
    return sorted(set(filter(None, names)))


def set_cookie_names(headers: list[dict]) -> list[str]:
    names = []
    for header in headers:
        if header.get("name", "").lower() == "set-cookie" and "=" in header.get("value", ""):
            names.append(header["value"].split("=", 1)[0].strip())
    return sorted(set(filter(None, names)))


def cookie_technologies(names: list[str]) -> list[dict]:
    findings = []
    for name in names:
        tech = COOKIE_TECH.get(name.lower())
        if tech:
            findings.append({"cookie": name, "technology": tech})
    return findings


def technology_headers(headers: list[dict]) -> list[dict]:
    findings = []
    for header in headers:
        name = header.get("name", "")
        lower = name.lower()
        if lower in TECH_HEADERS or lower.startswith("x-"):
            findings.append({"name": name, "value": header.get("value", "")})
    return findings


def infer_header_order(headers: list[dict]) -> str | None:
    order = [h.get("name", "").lower() for h in headers]
    if not order:
        return None
    first = order[:6]
    if len(first) >= 2 and first[0] == "date" and first[1] == "server":
        return "apache-like order: date, server, then content metadata"
    if first[:3] == ["date", "content-type", "server"]:
        return "nginx-like order: date, content-type, server"
    if "server" in first:
        server_index = first.index("server")
        if "content-type" in first[:server_index] and ("content-length" in first[:server_index] or "date" in first[:server_index]):
            return "nginx-like order: content metadata appears before server"
    return None


def path_signals(path: str) -> list[dict]:
    findings = []
    lower = (path or "").lower()
    suffix = Path(lower).suffix
    if suffix in EXTENSION_TECH:
        findings.append({"kind": "extension", "value": suffix, "meaning": EXTENSION_TECH[suffix]})
    for pattern, meaning in DEFAULT_FILE_PATTERNS.items():
        if lower == pattern.lower() or lower.endswith(pattern.lower()):
            findings.append({"kind": "default-file", "value": pattern, "meaning": meaning})
    parts = [part for part in lower.split("/") if part]
    for part in parts:
        if part in {"wp-admin", "wp-content", "wp-json"}:
            findings.append({"kind": "directory", "value": part, "meaning": "WordPress path convention"})
        elif part in {"sites", "modules", "themes"} and "drupal" in lower:
            findings.append({"kind": "directory", "value": part, "meaning": "Drupal path convention"})
        elif re.fullmatch(r"v[0-9]+", part):
            findings.append({"kind": "api-version", "value": part, "meaning": "versioned API path"})
    return findings


def malformed_request_signal(start_line: str) -> dict | None:
    if not start_line:
        return None
    parts = start_line.split()
    if len(parts) >= 3 and not re.fullmatch(r"HTTP/(1\.0|1\.1|2|3)", parts[2]):
        return {"kind": "invalid-http-version", "line": start_line}
    if parts and parts[0].upper() in MALFORMED_METHODS:
        return {"kind": "unusual-or-malformed-method", "line": start_line}
    return None


def default_error_signatures(status_code: int | None, body: str, raw: str) -> list[dict]:
    if status_code not in {400, 401, 403, 404, 405, 406, 408, 415, 429, 500, 502, 503, 504}:
        return []
    haystack = f"{raw[:2000]}\n{body[:4000]}"
    findings = []
    for technology, pattern in DEFAULT_ERROR_SIGNATURES:
        match = pattern.search(haystack)
        if match:
            findings.append({"technology": technology, "evidence": match.group(0)[:120]})
    return findings


def aggregate(records: list[dict]) -> dict:
    headers = defaultdict(Counter)
    cookie_counter = Counter()
    tech_header_values = defaultdict(Counter)
    header_order_guesses = Counter()
    error_signatures = Counter()
    path_signal_counter = Counter()
    cookie_technology_counter = Counter()
    status_counter = Counter()
    method_counter = Counter()
    host_counter = Counter()
    api_paths = []

    for record in records:
        host_counter[record.get("host") or ""] += 1
        method_counter[record.get("method") or ""] += 1
        status_counter[str(record["response"].get("statusCode"))] += 1
        if record.get("api_candidate"):
            api_paths.append(record.get("path"))
        for signal in record.get("path_signals", []):
            path_signal_counter[f"{signal['kind']}: {signal['value']} -> {signal['meaning']}"] += 1
        if record["request"].get("malformed_request_signal"):
            signal = record["request"]["malformed_request_signal"]
            path_signal_counter[f"captured malformed request: {signal['kind']}"] += 1
        for finding in record["request"].get("cookie_technologies", []):
            cookie_technology_counter[f"{finding['cookie']} -> {finding['technology']}"] += 1
        for finding in record["response"].get("set_cookie_technologies", []):
            cookie_technology_counter[f"{finding['cookie']} -> {finding['technology']}"] += 1
        if record["response"].get("header_order_guess"):
            header_order_guesses[record["response"]["header_order_guess"]] += 1
        for finding in record["response"].get("default_error_signatures", []):
            error_signatures[f"{finding['technology']}: {finding['evidence']}"] += 1
        for header in record["response"].get("headers", []):
            name = header.get("name", "").lower()
            headers["response"][name] += 1
            if name in TECH_HEADERS:
                tech_header_values[name][header.get("value", "")] += 1
        for name in record["request"].get("cookie_names", []):
            cookie_counter[name] += 1
        for name in record["response"].get("set_cookie_names", []):
            cookie_counter[name] += 1

    return {
        "hosts": host_counter.most_common(),
        "methods": method_counter.most_common(),
        "status_codes": status_counter.most_common(),
        "api_paths": sorted(set(filter(None, api_paths))),
        "cookie_names": cookie_counter.most_common(),
        "cookie_technologies": cookie_technology_counter.most_common(),
        "response_header_names": headers["response"].most_common(),
        "technology_header_values": {k: v.most_common() for k, v in tech_header_values.items()},
        "header_order_guesses": header_order_guesses.most_common(),
        "default_error_signatures": error_signatures.most_common(),
        "path_and_file_signals": path_signal_counter.most_common(),
    }


def host_fingerprints(records: list[dict], target_host: str) -> list[dict]:
    grouped: dict[str, list[dict]] = defaultdict(list)
    for record in records:
        grouped[record.get("host") or ""].append(record)
    if target_host not in grouped:
        grouped[target_host] = []

    fingerprints = []
    for host, host_records in sorted(grouped.items(), key=lambda item: (item[0] != target_host, item[0])):
        summary = aggregate(host_records) if host_records else empty_aggregate()
        score, reasons = api_score(host, host_records)
        fingerprints.append(
            {
                "host": host,
                "is_original_target_host": host == target_host,
                "request_count": len(host_records),
                "api_score": score,
                "api_reasons": reasons,
                "is_api_candidate": score >= 3 or host == target_host,
                "aggregate": summary,
            }
        )
    return fingerprints


def api_host_candidates(records: list[dict], target_host: str) -> list[dict]:
    candidates = [
        {
            "host": fingerprint["host"],
            "is_original_target_host": fingerprint["is_original_target_host"],
            "request_count": fingerprint["request_count"],
            "api_score": fingerprint["api_score"],
            "api_reasons": fingerprint["api_reasons"],
        }
        for fingerprint in host_fingerprints(records, target_host)
        if fingerprint["is_api_candidate"]
    ]
    return sorted(candidates, key=lambda item: (not item["is_original_target_host"], -item["api_score"], item["host"]))


def api_score(host: str, records: list[dict]) -> tuple[int, list[str]]:
    score = 0
    reasons = []
    labels = host.split(".")
    host_lower = host.lower()
    if any(label in {"api", "graphql", "rest", "gateway", "edge-api"} for label in labels):
        score += 5
        reasons.append("API-like hostname label")
    elif "api" in host_lower:
        score += 3
        reasons.append("API-like hostname substring")

    api_records = [record for record in records if record.get("api_candidate")]
    if api_records:
        score += min(5, len(api_records))
        reasons.append(f"{len(api_records)} API-like request(s)")

    content_types = Counter(
        (record.get("response", {}).get("content_type") or "").split(";")[0].lower()
        for record in records
        if record.get("response", {}).get("content_type")
    )
    api_content_types = [ct for ct in content_types if any(marker in ct for marker in ("json", "graphql", "grpc", "protobuf", "xml"))]
    if api_content_types:
        score += 2
        reasons.append("API content type(s): " + ", ".join(api_content_types[:4]))

    methods = {record.get("method", "").upper() for record in records}
    non_page_methods = sorted(methods - {"", "GET", "HEAD", "OPTIONS"})
    if non_page_methods:
        score += 2
        reasons.append("Non-page HTTP methods: " + ", ".join(non_page_methods))

    api_paths = sorted({record.get("path") for record in records if record.get("api_candidate") and record.get("path")})
    if api_paths:
        score += 2
        reasons.append("API path patterns: " + ", ".join(api_paths[:5]))

    if not records:
        reasons.append("No captured traffic for literal target host")
    return score, reasons


def empty_aggregate() -> dict:
    return {
        "hosts": [],
        "methods": [],
        "status_codes": [],
        "api_paths": [],
        "cookie_names": [],
        "cookie_technologies": [],
        "response_header_names": [],
        "technology_header_values": {},
        "header_order_guesses": [],
        "default_error_signatures": [],
        "path_and_file_signals": [],
    }


if __name__ == "__main__":
    raise SystemExit(main())
