QUERY = """
query FingerprintTraffic($limit: Int, $offset: Int, $filter: HTTPQLInput) {
  requestsByOffset(limit: $limit, offset: $offset, filter: $filter) {
    nodes {
      id
      host
      method
      path
      query
      port
      isTls
      createdAt
      raw
      response {
        id
        statusCode
        length
        roundtripTime
        raw
      }
    }
  }
}
""".strip()

